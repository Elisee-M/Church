function historyFor(seed: SpaceSeed): SpaceHistoryEntry[] {
  const entries: SpaceHistoryEntry[] = [];
  if (seed.occupiedSince) {
    entries.push({
      id: `${seed.id}-h1`,
      date: seed.occupiedSince,
      event: "Tenant moved in",
      description: `Agreement signed and ${seed.code} handed over in good condition.`,
    });
  } else {
    entries.push({
      id: `${seed.id}-h1`,
      date: seed.status === "maintenance" ? "2026-10-02" : "2026-09-01",
      event: seed.status === "maintenance" ? "Maintenance started" : "Space listed as vacant",
      description:
        seed.status === "maintenance"
          ? "Scheduled repairs and deep cleaning in progress."
          : "Marketing photos refreshed and listing shared with the church network.",
    });
  }
  entries.push({
    id: `${seed.id}-h2`,
    date: "2024-01-15",
    event: "Condition inspection",
    description: "Annual building inspection completed. No structural issues recorded.",
  });
  return entries;
}

export const spaces: Space[] = spaceSeeds.map((seed) => ({
  ...seed,
  features: seed.features.length ? seed.features : featureSets[seed.category],
  history: historyFor(seed),
}));

export const spaceCategoryCounts = spaces.reduce<Record<string, number>>((acc, space) => {
  acc[space.category] = (acc[space.category] ?? 0) + 1;
  return acc;
}, {});
